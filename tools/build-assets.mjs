// Builds the front-end assets into sitepizza/static/:
//   dist/site.min.css  = purged Bootstrap 5 subset + sitepizza/assets/css/style.css, minified
//   dist/site.min.js   = only the Bootstrap components in use + sitepizza/assets/js/site.js, minified
//   fonts/*.woff2      = self-hosted Fraunces + Source Sans 3 (trimmed by tools/subset-fonts.py)
//   ../icones_svg.py   = the Font Awesome icons the templates use, as inline SVG data
// Run: npm install && npm run build
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, statSync } from 'node:fs'
import { gzipSync } from 'node:zlib'
import { PurgeCSS } from 'purgecss'
import { transform, browserslistToTargets } from 'lightningcss'
import * as esbuild from 'esbuild'

const root = new URL('..', import.meta.url).pathname
const app = `${root}sitepizza/`
const out = `${app}static/`
const nm = `${root}node_modules/`

mkdirSync(`${out}dist`, { recursive: true })
mkdirSync(`${out}fonts`, { recursive: true })

/* Fonts ------------------------------------------------------------------------------------- */
// Trimmed by tools/subset-fonts.py (weight axis + Portuguese glyph set), committed in assets/fonts.
for (const f of ['fraunces-pt-wght.woff2', 'source-sans-3-pt-wght.woff2']) {
  copyFileSync(`${app}assets/fonts/${f}`, `${out}fonts/${f}`)
}

/* Icons ------------------------------------------------------------------------------------- */
const icones = {
  user: 'solid/user', 'shopping-cart': 'solid/shopping-cart', 'power-off': 'solid/power-off',
  'sign-in-alt': 'solid/sign-in-alt', 'user-plus': 'solid/user-plus', utensils: 'solid/utensils',
  phone: 'solid/phone', 'mobile-alt': 'solid/mobile-alt', envelope: 'solid/envelope',
  'map-marker-alt': 'solid/map-marker-alt', key: 'solid/key', 'money-bill-alt': 'regular/money-bill-alt',
  'credit-card': 'regular/credit-card', truck: 'solid/truck', map: 'regular/map',
  check: 'solid/check', minus: 'solid/minus', directions: 'solid/directions', plus: 'solid/plus', 'trash-alt': 'regular/trash-alt', camera: 'solid/camera',
  globe: 'solid/globe',
}
let py = '"""Inline SVG icons (Font Awesome Free 5.15.4, CC BY 4.0 - https://fontawesome.com/license/free).\n\n' +
  'Generated by tools/build-assets.mjs. Replaces the Font Awesome CSS + webfont (render-blocking,\n' +
  '~95 KB) with only the icons the site uses.\n"""\n\nICONES = {\n'
for (const [nome, ficheiro] of Object.entries(icones)) {
  const svg = readFileSync(`${nm}@fortawesome/fontawesome-free/svgs/${ficheiro}.svg`, 'utf8')
  py += `    "${nome}": ("${svg.match(/viewBox="([^"]+)"/)[1]}", "${svg.match(/ d="([^"]+)"/)[1]}"),\n`
}
writeFileSync(`${app}icones_svg.py`, py + '}\n')

/* JS ---------------------------------------------------------------------------------------- */
await esbuild.build({
  entryPoints: [`${app}assets/js/site.js`],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2019'],
  legalComments: 'none',
  outfile: `${out}dist/site.min.js`,
})

/* CSS --------------------------------------------------------------------------------------- */
const purged = await new PurgeCSS().purge({
  content: [
    `${app}templates/**/*.html`,
    `${app}templatetags/*.py`,
    `${app}assets/js/*.js`,
    // classes the Bootstrap components add at runtime
    `${nm}bootstrap/js/src/{alert,carousel,collapse,base-component}.js`,
  ],
  css: [`${nm}bootstrap/dist/css/bootstrap.css`],
  safelist: {
    standard: ['show', 'fade', 'active', 'collapsing', 'collapse', 'pointer-event', 'visually-hidden', 'btn-close', 'form-control'],
    greedy: [/^alert/, /^carousel/],   // Django message tags (alert-success, alert-danger, ...) + carousel states
  },
  variables: true,
  keyframes: true,
  fontFace: true,
})

const css = purged[0].css + '\n' + readFileSync(`${app}assets/css/style.css`, 'utf8')
const { code } = transform({
  filename: 'site.css',
  code: Buffer.from(css),
  minify: true,
  // keep image-set() fallbacks etc. sensible for real-world browsers
  targets: browserslistToTargets(['> 0.5%', 'last 2 versions', 'Firefox ESR', 'not dead']),
})
// Lightning CSS writes image-set("a.webp" ...) with bare strings; Django's ManifestStaticFilesStorage only
// rewrites url(...), so put url() back or the textures keep unhashed, short-cached names.
const css2 = code.toString().replace(/image-set\(([^;{}]*?)\)(?=[;}])/g, (m, inner) =>
  'image-set(' + inner.replace(/(^|,)\s*"([^"]+)"/g, '$1url("$2")') + ')')
writeFileSync(`${out}dist/site.min.css`, css2)

/* Report ------------------------------------------------------------------------------------ */
const kb = (n) => `${(n / 1024).toFixed(1)} KB`
for (const f of ['dist/site.min.css', 'dist/site.min.js', 'fonts/fraunces-pt-wght.woff2', 'fonts/source-sans-3-pt-wght.woff2']) {
  const buf = readFileSync(out + f)
  console.log(`${f.padEnd(46)} ${kb(statSync(out + f).size).padStart(9)}  (gzip ${kb(gzipSync(buf).length)})`)
}
